"""Prepare Git timestamps for the homepage without modifying Markdown files."""

import json
from datetime import datetime, timezone
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
OUTPUT = ROOT / "overrides/partials/generated-news-dates.html"


def iso_timestamp(seconds):
    return datetime.fromtimestamp(int(seconds), timezone.utc).isoformat(
        timespec="seconds"
    )


def main():
    shallow = subprocess.run(
        ["git", "rev-parse", "--is-shallow-repository"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout.strip()
    if shallow == "true":
        raise SystemExit("Нужна полная история Git: выполните git fetch --unshallow.")

    dates = {}
    for language in ("ru", "en"):
        for path in sorted((DOCS / language / "news").rglob("*.md")):
            timestamps = subprocess.run(
                ["git", "log", "--follow", "--format=%ct", "--", str(path.relative_to(ROOT))],
                cwd=ROOT, check=True, capture_output=True, text=True,
            ).stdout.splitlines()
            # Uncommitted new files still appear in local previews.
            created = timestamps[-1] if timestamps else path.stat().st_mtime
            updated = timestamps[0] if timestamps else path.stat().st_mtime
            dates[path.relative_to(DOCS).as_posix()] = {
                "created": iso_timestamp(created),
                "updated": iso_timestamp(updated),
            }

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    # JSON string quoting is also valid in these MiniJinja dictionary literals.
    literal = json.dumps(dates, ensure_ascii=True)
    OUTPUT.write_text(
        "{# Generated by scripts/collect_news_dates.py; do not edit. #}\n"
        "{% set history.dates = " + literal + " %}\n",
        encoding="utf-8",
    )
    print(f"Даты новостей подготовлены: {len(dates)}")


if __name__ == "__main__":
    main()
